#!/usr/bin/env bash
# One-time macOS setup for building and running MedTagger.
#
# Installs (via Homebrew): JDK 11, Apache Maven, Apache Ant.
# Writes ~/.medtagger/env.sh with JAVA_HOME, PATH and the GitHub credentials
# Maven needs to download the OHNLP Backbone dependency from GitHub Packages.
#
# Usage:  bash scripts/setup_mac_env.sh
set -euo pipefail

say()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31mxx\033[0m %s\n' "$*" >&2; exit 1; }

[[ "$(uname -s)" == "Darwin" ]] || die "This script is for macOS."

# --- 1. Homebrew -----------------------------------------------------------
if ! command -v brew >/dev/null 2>&1; then
  # Homebrew may be installed but not on PATH yet (fresh shell on Apple Silicon)
  for p in /opt/homebrew/bin/brew /usr/local/bin/brew; do
    [[ -x "$p" ]] && eval "$("$p" shellenv)" && break
  done
fi
if ! command -v brew >/dev/null 2>&1; then
  say "Homebrew not found. Installing it (you may be asked for your Mac password)..."
  /bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"
  for p in /opt/homebrew/bin/brew /usr/local/bin/brew; do
    [[ -x "$p" ]] && eval "$("$p" shellenv)" && break
  done
fi
command -v brew >/dev/null 2>&1 || die "Homebrew install failed. See https://brew.sh"
BREW_BIN="$(command -v brew)"
say "Homebrew: $BREW_BIN"

# --- 2. Java 11, Maven, Ant -------------------------------------------------
# pom.xml compiles for Java 11, so JDK 11 is the safest match.
say "Installing openjdk@11, maven, ant (already-installed ones are skipped)..."
for pkg in openjdk@11 maven ant; do
  if brew list --versions "$pkg" >/dev/null 2>&1; then
    echo "   $pkg already installed"
  else
    brew install "$pkg"
  fi
done

JDK_PREFIX="$(brew --prefix openjdk@11)"
JAVA_HOME_DIR="$JDK_PREFIX/libexec/openjdk.jdk/Contents/Home"
[[ -x "$JAVA_HOME_DIR/bin/java" ]] || die "JDK 11 not found at $JAVA_HOME_DIR"

# --- 3. GitHub Packages credentials ----------------------------------------
# The Backbone API dependency lives on GitHub Packages, which requires a
# personal access token (classic) with the read:packages scope, even though
# the package is public. Create one at https://github.com/settings/tokens
ENV_DIR="$HOME/.medtagger"
ENV_FILE="$ENV_DIR/env.sh"
mkdir -p "$ENV_DIR"

OLD_ACTOR=""; OLD_TOKEN=""
if [[ -f "$ENV_FILE" ]]; then
  OLD_ACTOR="$(grep -E '^export SECRET_ACTOR=' "$ENV_FILE" | cut -d= -f2- | tr -d '"' || true)"
  OLD_TOKEN="$(grep -E '^export SECRET_TOKEN=' "$ENV_FILE" | cut -d= -f2- | tr -d '"' || true)"
fi

echo
say "Maven needs a GitHub token with the read:packages scope."
echo "    Create one at: https://github.com/settings/tokens  (Tokens (classic) -> read:packages)"
read -r -p "    GitHub username [${OLD_ACTOR:-none}]: " GH_ACTOR
GH_ACTOR="${GH_ACTOR:-$OLD_ACTOR}"
read -r -s -p "    GitHub token (input hidden, Enter to keep existing): " GH_TOKEN; echo
GH_TOKEN="${GH_TOKEN:-$OLD_TOKEN}"
[[ -n "$GH_ACTOR" && -n "$GH_TOKEN" ]] || warn "No GitHub credentials given. The Maven build will fail until you rerun this script."

# --- 4. Write env file -----------------------------------------------------
umask 077
cat > "$ENV_FILE" <<EOF
# Generated by MedTagger scripts/setup_mac_env.sh — source this file.
eval "\$($BREW_BIN shellenv)"
export JAVA_HOME="$JAVA_HOME_DIR"
export PATH="\$JAVA_HOME/bin:\$PATH"
export SECRET_ACTOR="$GH_ACTOR"
export SECRET_TOKEN="$GH_TOKEN"
EOF
chmod 600 "$ENV_FILE"
say "Wrote $ENV_FILE (readable only by you)"

# --- 5. Optionally load it in every new terminal ---------------------------
RC="$HOME/.zshrc"; [[ "${SHELL:-}" == */bash ]] && RC="$HOME/.bash_profile"
LINE='[ -f "$HOME/.medtagger/env.sh" ] && source "$HOME/.medtagger/env.sh"'
if ! grep -qF "$LINE" "$RC" 2>/dev/null; then
  read -r -p "Add MedTagger env to $RC so java/mvn/ant work in new terminals? [Y/n] " yn
  if [[ ! "$yn" =~ ^[Nn] ]]; then
    printf '\n# MedTagger\n%s\n' "$LINE" >> "$RC"
    say "Added to $RC"
  fi
fi

# --- 6. Verify -------------------------------------------------------------
# shellcheck disable=SC1090
source "$ENV_FILE"
echo
say "Versions:"
java -version 2>&1 | head -1 || true
mvn -v 2>/dev/null | head -1 || true
ant -version
echo
say "Done. Next: bash scripts/quickstart.sh"
echo "    (In this terminal run:  source ~/.medtagger/env.sh  to use java/mvn/ant directly.)"
